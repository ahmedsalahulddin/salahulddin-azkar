/// Returns the string for [key] in the current app locale — or, for the
/// memorisation section's own keys, in the language chosen at the top of
/// that tab, or for the Account & Settings screen's own keys, in the
/// language chosen at the top of that screen.
String t(String key) {
  if (key.startsWith('tahfeez.')) {
    final code = TahfeezLang.code;
    final map = switch (code) {
      'ar' => _ar,
      'en' => _en,
      _ => tahfeezTranslations[code] ?? _en,
    };
    return map[key] ?? _en[key] ?? _ar[key] ?? key;
  }
  if (accountTranslations['fr']!.containsKey(key)) {
    final code = AccountLang.code;
    final map = switch (code) {
      'ar' => _ar,
      'en' => _en,
      _ => accountTranslations[code] ?? _en,
    };
    return map[key] ?? _en[key] ?? _ar[key] ?? key;
  }
  if (appTranslations['fr']!.containsKey(key)) {
    final code = AppLocale.code;
    final map = switch (code) {
      'ar' => _ar,
      'en' => _en,
      _ => appTranslations[code] ?? _en,
    };
    return map[key] ?? _en[key] ?? _ar[key] ?? key;
  }
  final map = AppLocale.isEn ? _en : _ar;
  return map[key] ?? key;
}

/// A card name in Arabic, with its rendering in the reader's chosen language
/// in parentheses on the same line — Arabic stays the one language of
/// record, the parenthetical is a hint back to it. Arabic readers see just
/// the Arabic, unchanged.
String tBoth(String key) {
  final ar = _ar[key] ?? key;
  final code = AppLocale.code;
  if (code == 'ar') return ar;
  final other = code == 'en'
      ? _en[key]
      : (appTranslations[code]?[key] ?? _en[key]);
  if (other == null || other == ar) return ar;
  return '$ar ($other)';
}

/// Splits a [tBoth] string back into its Arabic and English halves, so a
/// caller can lay them out as two separate lines instead of one that wraps —
/// a wrapped "Arabic (English)" string breaks the parenthetical apart under
/// RTL/LTR bidi reordering once it no longer fits on a single line.
(String, String?) splitBilingual(String combined) {
  final i = combined.lastIndexOf(' (');
  if (i == -1 || !combined.endsWith(')')) return (combined, null);
  return (
    combined.substring(0, i),
    combined.substring(i + 2, combined.length - 1),
  );
}

