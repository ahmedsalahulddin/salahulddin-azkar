/// One story: a title, its body, and where it comes from.
///
/// The body is a retelling in plain language, not a translation of the
/// source — the source citation is what to check against if the reader
/// wants the words as the Qur'an or the hadith collection has them.
class Story {
  final String id;
  final String categoryId;
  final String title;
  final String body;
  final String source;

  const Story({
    required this.id,
    required this.categoryId,
    required this.title,
    required this.body,
    required this.source,
  });
}

class StoryCategory {
  final String id;
  final String name;
  final String icon;
  final String description;
  int count;

  StoryCategory({
    required this.id,
    required this.name,
    required this.icon,
    required this.description,
    this.count = 0,
  });
}

